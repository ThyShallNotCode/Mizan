#!/usr/bin/env python3
"""Generate crates/omr-model/src/catalogue.rs from Appendix A of docs/TECHNICAL_DESIGN.md.

Appendix A is the single authority for exception codes (spec §13.1). The generated table is
checked in; `cargo test -p omr-model` fails if it drifts from the spec (see tests/catalogue.rs).
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
doc = (ROOT / "docs" / "TECHNICAL_DESIGN.md").read_text(encoding="utf-8").splitlines()
start = next(i for i, l in enumerate(doc) if l.startswith("## Appendix A"))
end = next(i for i, l in enumerate(doc) if l.startswith("## Appendix B"))

SEV = {"BLOCKER": "Blocker", "ERROR": "Error", "WARN": "Warn", "INFO": "Info"}
SCOPES = ["Page", "Region", "Item", "Booklet", "Student", "Batch", "Exam", "Course", "OutcomeReport", "Document"]

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

rows = []
for l in doc[start:end]:
    m = re.match(r"\|\s*\**((CAP|REG|IDN|COL|MRK|SCO|SYS)-\d{3})\**\s*\|", l)
    if not m:
        continue
    cells = [c.strip() for c in l.strip().strip("|").split("|")]
    code, case = cells[0].strip("*"), cells[1]
    sev_cell, scope_cell, owner = cells[-3], cells[-2], cells[-1]
    sevs = [SEV[s] for s in re.findall(r"BLOCKER|ERROR|WARN|INFO", sev_cell)]
    scopes = [s for s in SCOPES if re.search(r"\b" + s + r"\b", scope_cell)]
    title = re.split(r"\.\s+Sub-reasons?|\(", case)[0].strip().rstrip(".")
    rows.append((code, title, sevs, scopes, owner))

out = ["// @generated by scripts/gen_exception_catalogue.py from docs/TECHNICAL_DESIGN.md Appendix A.",
       "// Do not edit by hand: regenerate with `python3 scripts/gen_exception_catalogue.py`.",
       "use crate::exceptions::{ExceptionDef, Scope, Severity};",
       "",
       f"/// Every exception code defined in Appendix A ({len(rows)} codes).",
       "pub const CATALOGUE: &[ExceptionDef] = &["]
for code, title, sevs, scopes, owner in rows:
    out.append("    ExceptionDef {")
    out.append(f'        code: "{code}",')
    out.append(f'        title: "{esc(title)}",')
    out.append("        severities: &[" + ", ".join(f"Severity::{s}" for s in sevs) + "],")
    out.append("        scopes: &[" + ", ".join(f"Scope::{s}" for s in scopes) + "],")
    out.append(f'        owner: "{esc(owner)}",')
    out.append("    },")
out.append("];")
dst = ROOT / "crates" / "omr-model" / "src" / "catalogue.rs"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {dst} with {len(rows)} codes")

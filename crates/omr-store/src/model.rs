    fn page_rows(&self, where_sql: &str, p: impl rusqlite::Params) -> Result<Vec<PageRecord>> {
        let sql = format!(
            "SELECT page_id, batch_id, source_id, page_index, object, source_sha384, state, \
             quarantine_reason, booklet_id, page_no, imprint, dpi_x, dpi_y, capture_kind, \
             registration FROM page {where_sql}"
        );
        let mut stmt = self.conn.prepare(&sql)?;
        let rows = stmt.query_map(p, |r| {
            Ok((
                (
                    r.get::<_, String>(0)?,
                    r.get::<_, String>(1)?,
                    r.get::<_, Option<String>>(2)?,
                    r.get::<_, i64>(3)?,
                    r.get::<_, String>(4)?,
                    r.get::<_, String>(5)?,
                    r.get::<_, String>(6)?,
                ),
                (
                    r.get::<_, Option<String>>(7)?,
                    r.get::<_, Option<String>>(8)?,
                    r.get::<_, Option<u16>>(9)?,
                    r.get::<_, Option<String>>(10)?,
                    r.get::<_, Option<u32>>(11)?,
                    r.get::<_, Option<u32>>(12)?,
                    r.get::<_, Option<String>>(13)?,
                    r.get::<_, Option<String>>(14)?,
                ),
            ))
        })?;
        rows.map(|t| {
            let (a, b) = t?;
            Ok(PageRecord {
                page_id: a.0,
                batch_id: a.1,
                source_id: a.2,
                page_index: a.3,
                object: a.4,
                source_sha384: a.5,
                state: PageState::parse(&a.6)?,
                quarantine_reason: b.0,
                booklet_id: b.1,
                page_no: b.2,
                imprint: b.3,
                dpi: b.4.zip(b.5),
                capture_kind: b.6,
                registration: b.7.map(|t| serde_json::from_str(&t)).transpose()?,
            })
        })
        .collect()
    }

    /// Pages of a batch in index order.
    pub fn pages(&self, batch_id: &str) -> Result<Vec<PageRecord>> {
        self.page_rows(
            "WHERE batch_id = ?1 ORDER BY page_index, page_id",
            [batch_id],
        )
    }

    /// One page.
    pub fn page(&self, page_id: &str) -> Result<PageRecord> {
        self.page_rows("WHERE page_id = ?1", [page_id])?
            .pop()
            .ok_or_else(|| StoreError::NotFound(format!("page {page_id}")))
    }

    /// Page IDs referencing an object.
    pub fn pages_for_object(&self, blake3: &str) -> Result<Vec<String>> {
        let mut stmt = self
            .conn
            .prepare("SELECT page_id FROM page WHERE object = ?1 ORDER BY page_id")?;
        Ok(stmt
            .query_map([blake3], |r| r.get(0))?
            .collect::<rusqlite::Result<_>>()?)
    }

    /// Per-question results of one page in one run.
    pub fn question_results(&self, run_id: &str, page_id: &str) -> Result<Vec<StoredQuestion>> {
        let mut stmt = self.conn.prepare(
            "SELECT question, response, auto_accepted, logit_milli, codes FROM question_result \
             WHERE run_id = ?1 AND page_id = ?2 ORDER BY question",
        )?;
        let rows = stmt.query_map(params![run_id, page_id], |r| {
            Ok((
                r.get::<_, u16>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, bool>(2)?,
                r.get::<_, i32>(3)?,
                r.get::<_, String>(4)?,
            ))
        })?;
        rows.map(|t| {
            let (question, resp, auto_accepted, logit, codes) = t?;
            Ok(StoredQuestion {
                question,
                response: serde_json::from_str(&resp)?,
                auto_accepted,
                logit: LogitMilli(logit),
                codes: codes.split_whitespace().map(str::to_owned).collect(),
            })
        })
        .collect()
    }

    /// Exceptions, optionally only those in `state` (`open` or `resolved`).
    pub fn exceptions(&self, state: Option<&str>) -> Result<Vec<StoredException>> {
        let mut stmt = self.conn.prepare(
            "SELECT exception_id, code, sub_reason, severity, scope, subject, detail, state, \
             run_id, page_id FROM exception WHERE ?1 IS NULL OR state = ?1 ORDER BY exception_id",
        )?;
        let rows = stmt.query_map([state], |r| {
            Ok((
                r.get::<_, i64>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, Option<String>>(2)?,
                r.get::<_, String>(3)?,
                r.get::<_, String>(4)?,
                r.get::<_, String>(5)?,
                r.get::<_, String>(6)?,
                r.get::<_, String>(7)?,
                r.get::<_, Option<String>>(8)?,
                r.get::<_, Option<String>>(9)?,
            ))
        })?;
        rows.map(|t| {
            let t = t?;
            // Rebuilt through the Appendix A catalogue: a stored row outside it is an
            // integrity failure, never an exception the app would act on.
            let mut exception = Exception::new(&t.1, parse_sev(&t.3)?, parse_scope(&t.4)?)
                .map_err(|e| StoreError::Integrity(format!("stored exception {}: {e}", t.0)))?
                .with_target(serde_json::from_str(&t.5)?)
                .with_detail(t.6);
            exception.sub_reason = t.2;
            Ok(StoredException {
                exception_id: t.0,
                exception,
                state: t.7,
                run_id: t.8,
                page_id: t.9,
            })
        })
        .collect()
    }


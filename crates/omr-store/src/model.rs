//! Typed records of the logical model (spec §14.3, MVP subset) with their writes on [`Tx`] and
//! reads on [`Reader`].
//!
//! Each state change appends its event in the same transaction (hybrid model, §14.4).
//! Content-addressed rows (template revisions, policy versions, mapping sets, roster snapshots,
//! pinned bodies, form maps) are keyed by the SHA-384 of their JCS form and never updated.
//! Student-linked values in events are `{ref, sha384}` commitments: `sha384 = SHA-384(nonce ‖
//! JCS(value))` with a per-row random nonce kept in the projection row. With encryption at
//! rest (deferred, §19.2) the digest becomes the ciphertext digest of the spec.


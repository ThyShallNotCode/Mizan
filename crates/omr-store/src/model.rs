    /// Stores one page's recognition output: per-question results, exceptions, the
    /// registration record and the page state `read` (`PageRecognized`, counts only).
    pub fn record_page_recognition(&mut self, run_id: &str, p: &PageRecognition) -> Result<()> {
        let manifest: String = self
            .conn()
            .query_row(
                "SELECT engine_manifest_sha384 FROM recognition_run WHERE run_id = ?1",
                [run_id],
                |r| r.get(0),
            )
            .optional()?
            .ok_or_else(|| StoreError::NotFound(format!("recognition run {run_id}")))?;
        let mut auto = 0usize;
        let mut codes_total = 0usize;
        for q in &p.questions {
            let mut codes: Vec<&str> = q.exceptions.iter().map(|e| e.code.as_str()).collect();
            codes.sort_unstable();
            codes.dedup();
            codes_total += q.exceptions.len();
            auto += usize::from(q.auto_accepted);
            self.conn().execute(
                "INSERT INTO question_result (run_id, page_id, question, response, auto_accepted, \
                 logit_milli, codes) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
                params![
                    run_id,
                    p.page_id,
                    q.question,
                    json_text(&q.response)?,
                    q.auto_accepted,
                    q.logit.0,
                    codes.join(" ")
                ],
            )?;
            for e in &q.exceptions {
                self.insert_exception(e, Some(run_id), Some(&p.page_id))?;
            }
        }
        for e in &p.exceptions {
            self.insert_exception(e, Some(run_id), Some(&p.page_id))?;
        }
        let n = self.conn().execute(
            "UPDATE page SET state = 'read', registration = ?2, version = version + 1 \
             WHERE page_id = ?1",
            params![p.page_id, jcs::value_to_jcs(&p.registration)?],
        )?;
        if n != 1 {
            return Err(StoreError::NotFound(format!("page {}", p.page_id)));
        }
        self.append_event(
            &NewEvent::new(
                "PageRecognized",
                "page",
                &p.page_id,
                Actor::engine("recog"),
                json!({
                    "run": run_id,
                    "questions": p.questions.len(),
                    "auto_accepted": auto,
                    "question_exceptions": codes_total,
                    "page_exceptions": p.exceptions.iter().map(|e| e.code.clone()).collect::<Vec<_>>(),
                }),
            )
            .with_engine_manifest(&manifest),
        )?;
        Ok(())
    }


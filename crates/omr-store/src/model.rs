fn commit_value(v: &Value) -> Result<(String, String)> {
    let mut seed = uuid::Uuid::now_v7().as_bytes().to_vec();
    seed.extend_from_slice(uuid::Uuid::now_v7().as_bytes());
    let nonce = hex::encode(&jcs::sha384(&seed)[..16]);
    let mut buf = hex::decode(&nonce).unwrap_or_default();
    buf.extend_from_slice(jcs::value_to_jcs(v)?.as_bytes());
    Ok((nonce, jcs::sha384_hex(&buf)))
}

/// Engines never perform decision actions (§14.4, §15.5): `SetResponse`, `ConfirmIdentity`,
/// `PublishKeyVersion` and `PublishPolicyVersion` need a human principal.
fn require_human(actor: &Actor, action: &str) -> Result<()> {
    if actor.is_engine() {
        return Err(StoreError::Invalid(format!(
            "engines never perform decision actions: {action} needs a human actor"
        )));
    }
    Ok(())
}

fn json_text<T: Serialize>(v: &T) -> Result<String> {
    Ok(jcs::to_jcs(v)?)
}

fn sev_str(s: Severity) -> &'static str {
    match s {
        Severity::Info => "info",
        Severity::Warn => "warn",
        Severity::Error => "error",
        Severity::Blocker => "blocker",
    }
}

fn parse_sev(s: &str) -> Result<Severity> {
    Ok(match s {
        "info" => Severity::Info,
        "warn" => Severity::Warn,
        "error" => Severity::Error,
        "blocker" => Severity::Blocker,
        _ => return Err(StoreError::Invalid(format!("severity {s:?}"))),
    })
}


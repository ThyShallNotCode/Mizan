fn parse_exam_id(s: &str) -> Result<ExamId> {
    uuid::Uuid::parse_str(s)
        .map(ExamId)
        .map_err(|_| StoreError::Invalid(format!("exam id {s:?}")))
}

fn verify_text(text: &str, sha384: &str) -> Result<()> {
    if jcs::sha384_hex(text.as_bytes()) != sha384 {
        return Err(StoreError::Integrity(format!(
            "content-addressed row {sha384} does not match its hash"
        )));
    }
    Ok(())
}

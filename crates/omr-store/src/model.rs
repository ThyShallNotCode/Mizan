    /// Stores a staged original and its page in one transaction; an exact duplicate of an
    /// ingested object raises CAP-011 (INFO) and adds no page (§14.5 "Deduplication").
    pub fn spool_page(
        &mut self,
        batch_id: &str,
        page_id: &str,
        page_index: i64,
        obj: &StagedObject,
        actor: &Actor,
    ) -> Result<SpoolOutcome> {
        if !self.insert_object(obj, ObjectKind::Original)? {
            // The BLAKE3 address is a non-security dedup hint: a duplicate is confirmed only by
            // an equal plaintext SHA-384 and length (§14.5, Appendix A CAP-011). Anything else
            // must not be dropped as a "duplicate".
            let (sha, len): (String, i64) = self.conn().query_row(
                "SELECT sha384, len FROM object WHERE blake3 = ?1",
                [&obj.blake3],
                |r| Ok((r.get(0)?, r.get(1)?)),
            )?;
            if sha != obj.sha384 || u64::try_from(len).ok() != Some(obj.len) {
                return Err(StoreError::ObjectCorrupt {
                    address: obj.blake3.clone(),
                    detail: "dedup address hit with a different SHA-384 or length".into(),
                });
            }
            let existing_pages = self.reader().pages_for_object(&obj.blake3)?;
            let exception = Exception::must("CAP-011", Severity::Info, Scope::Page)
                .with_target(Target {
                    page: Some(page_id.to_owned()),
                    ..Target::default()
                })
                .with_detail(format!(
                    "byte-identical to {} already ingested",
                    existing_pages.join(", ")
                ));
            return Ok(SpoolOutcome::Duplicate {
                existing_pages,
                exception,
            });
        }
        self.add_page(
            &PageRecord::spooled(page_id, batch_id, page_index, obj),
            actor,
        )?;
        Ok(SpoolOutcome::Spooled {
            page_id: page_id.into(),
        })
    }


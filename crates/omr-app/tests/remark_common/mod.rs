//! Synthetic Remark Office OMR graded workbooks for the import and parallel-run tests: the
//! sheet names and header layout of Remark's Advanced Grade Excel export (Student Response
//! Report, Student Statistics Report with learning-objective groups, Test Statistics Report),
//! filled with invented IDs, invented Arabic names and computed totals. No real data.
#![allow(dead_code)]

use rust_xlsxwriter::{Workbook, Worksheet};

/// The sheet names of a Remark graded workbook, in Remark's order.
pub const SHEETS: [&str; 11] = [
    "Student Statistics Report",
    "Class Frequency Distribution Re",
    "Test Statistics Report",
    "Student Response Report",
    "Condensed Test Report",
    "Class Learning Objective Report",
    "Student Achievement Report",
    "Detailed Item Analysis Report",
    "Item Analysis Graph Report",
    "Condensed Item Analysis Report",
    "Test Item Statistics Report",
];

/// How an ID cell is written.
#[derive(Clone, Debug)]
pub enum Id {
    /// A text cell.
    Text(String),
    /// A number cell (Excel-typed ID).
    Number(f64),
    /// Empty.
    Empty,
}

/// One student row.
#[derive(Clone, Debug)]
pub struct Student {
    /// ID cell.
    pub id: Id,
    /// Name (invented; Arabic).
    pub name: String,
    /// Section.
    pub section: String,
    /// Version as Remark writes it (`A`, `BLANK`).
    pub version: String,
    /// Answers as Remark writes them (`B`, `` empty).
    pub answers: Vec<String>,
    /// A total to write instead of the computed one (a hand-edited total).
    pub total_override: Option<f64>,
}

impl Student {
    /// A student with a text ID.
    pub fn new(id: &str, version: &str, answers: &[&str]) -> Self {
        Self {
            id: Id::Text(id.into()),
            name: "طالب تجريبي".into(),
            section: "1001".into(),
            version: version.into(),
            answers: answers.iter().map(|a| (*a).to_string()).collect(),
            total_override: None,
        }
    }
}

/// A workbook to write.
#[derive(Clone, Debug)]
pub struct Book {
    /// `Section No` and `Gender` columns (the ARTI-like layout) or not (the CS-like one).
    pub sections: bool,
    /// Key letters.
    pub key: Vec<String>,
    /// Points per question (for the totals and the groups).
    pub points: Vec<f64>,
    /// Learning-objective groups: name and 1-based question range (inclusive).
    pub groups: Vec<(String, u16, u16)>,
    /// Students.
    pub students: Vec<Student>,
    /// The Mean footer row.
    pub footer: bool,
}

impl Book {
    /// Remark's total of a student.
    pub fn total(&self, s: &Student) -> f64 {
        s.total_override.unwrap_or_else(|| {
            (0..self.key.len())
                .filter(|q| s.answers[*q] == self.key[*q])
                .map(|q| self.points[q])
                .sum()
        })
    }

    fn possible(&self) -> f64 {
        self.points.iter().sum()
    }

    fn group_points(&self, s: &Student, a: u16, b: u16) -> (f64, f64) {
        let qs = (a - 1) as usize..b as usize;
        let got = qs
            .clone()
            .filter(|q| s.answers[*q] == self.key[*q])
            .map(|q| self.points[q])
            .sum();
        let poss = qs.map(|q| self.points[q]).sum();
        (got, poss)
    }
}

fn id_cell(ws: &mut Worksheet, r: u32, c: u16, id: &Id) {
    match id {
        Id::Text(s) => {
            ws.write_string(r, c, s).unwrap();
        }
        Id::Number(f) => {
            ws.write_number(r, c, *f).unwrap();
        }
        Id::Empty => {}
    }
}

/// The workbook's bytes.
pub fn xlsx(b: &Book) -> Vec<u8> {
    xlsx_relabelled(b, &|l| l.to_string())
}

/// The workbook's bytes with the learning-objective headers rewritten by `relabel` (e.g. a
/// group naming a question the test does not have).
pub fn xlsx_relabelled(b: &Book, relabel: &dyn Fn(&str) -> String) -> Vec<u8> {
    let mut wb = Workbook::new();
    let n = b.key.len();
    for name in SHEETS {
        let ws = wb.add_worksheet();
        ws.set_name(name).unwrap();
        match name {
            "Student Response Report" => response(ws, b, n),
            "Student Statistics Report" => statistics(ws, b, relabel),
            "Test Statistics Report" => test_stats(ws, b),
            _ => {
                ws.write_string(1, 0, name).unwrap();
            }
        }
    }
    wb.save_to_buffer().unwrap()
}

fn response(ws: &mut Worksheet, b: &Book, n: usize) {
    ws.write_string(1, 0, "Student Response Report").unwrap();
    ws.write_string(3, 0, "Generated By Remark® From Gravic, Inc.")
        .unwrap();
    let mut header: Vec<String> = vec!["Student ID".into(), "Student Name".into()];
    if b.sections {
        header.push("Section No".into());
        header.push("Gender".into());
    }
    for h in ["Version1", "Total", "Percent", "Grade"] {
        header.push(h.into());
    }
    let a0 = header.len() as u16;
    for q in 1..=n {
        header.push(format!("Answers{q}"));
    }
    for (c, h) in header.iter().enumerate() {
        ws.write_string(5, c as u16, h).unwrap();
    }
    let c_total = a0 - 3;
    ws.write_string(6, 0, "Answer Key").unwrap();
    ws.write_number(6, c_total, b.possible()).unwrap();
    for (q, k) in b.key.iter().enumerate() {
        ws.write_string(6, a0 + q as u16, k).unwrap();
    }
    for (r, s) in (7u32..).zip(&b.students) {
        id_cell(ws, r, 0, &s.id);
        ws.write_string(r, 1, &s.name).unwrap();
        let mut c = 2u16;
        if b.sections {
            ws.write_string(r, 2, &s.section).unwrap();
            ws.write_string(r, 3, "Male").unwrap();
            c = 4;
        }
        ws.write_string(r, c, &s.version).unwrap();
        let t = b.total(s);
        ws.write_number(r, c + 1, t).unwrap();
        ws.write_number(r, c + 2, 100.0 * t / b.possible()).unwrap();
        ws.write_string(r, c + 3, "C").unwrap();
        for (q, a) in s.answers.iter().enumerate() {
            if !a.is_empty() {
                ws.write_string(r, a0 + q as u16, a).unwrap();
            }
        }
    }
    if b.footer {
        let r = 7 + b.students.len() as u32;
        ws.write_string(r, 0, "Mean").unwrap();
        let mean = b.students.iter().map(|s| b.total(s)).sum::<f64>() / b.students.len() as f64;
        ws.write_number(r, c_total, mean).unwrap();
        ws.write_string(r, c_total + 2, "C").unwrap();
        for q in 0..n {
            ws.write_number(r, a0 + q as u16, 0.5).unwrap();
        }
    }
}

fn statistics(ws: &mut Worksheet, b: &Book, relabel: &dyn Fn(&str) -> String) {
    ws.write_string(1, 0, "Student Statistics Report").unwrap();
    ws.write_string(3, 0, "Generated By Remark® From Gravic, Inc.")
        .unwrap();
    // The ARTI-like layout: 6 columns per block; Overall at column 5.
    let base = if b.sections { 5u16 } else { 3 };
    ws.write_string(5, base + 4, "Benchmark: ").unwrap();
    ws.write_number(5, base + 5, 60.0).unwrap();
    ws.write_string(6, 0, "Overall").unwrap();
    for (k, (g, a, z)) in b.groups.iter().enumerate() {
        let c = base + 6 * (k as u16 + 1);
        ws.write_string(6, c, relabel(&format!("{g} ({a}-{z})")))
            .unwrap();
    }
    let mut header = vec!["Student ID", "Student Name"];
    if b.sections {
        header.extend(["Section No", "Gender"]);
    }
    header.push("Version1");
    for (c, h) in header.iter().enumerate() {
        ws.write_string(7, c as u16, *h).unwrap();
    }
    for k in 0..=b.groups.len() as u16 {
        let c = base + 6 * k;
        ws.write_string(7, c, "Grade").unwrap();
        ws.write_string(7, c + 1, "Total").unwrap();
        ws.write_string(7, c + 4, "Percent").unwrap();
    }
    for (r, s) in (8u32..).zip(&b.students) {
        id_cell(ws, r, 0, &s.id);
        ws.write_string(r, 1, &s.name).unwrap();
        if b.sections {
            ws.write_string(r, 2, &s.section).unwrap();
            ws.write_string(r, 3, "Male").unwrap();
        }
        ws.write_string(r, header.len() as u16 - 1, &s.version)
            .unwrap();
        let mut blocks = vec![(b.total(s), b.possible())];
        for (_, a, z) in &b.groups {
            blocks.push(b.group_points(s, *a, *z));
        }
        for (k, (got, poss)) in blocks.into_iter().enumerate() {
            let c = base + 6 * k as u16;
            ws.write_string(r, c, "C").unwrap();
            ws.write_number(r, c + 1, got).unwrap();
            ws.write_string(r, c + 2, "/").unwrap();
            ws.write_number(r, c + 3, poss).unwrap();
            ws.write_number(r, c + 4, 100.0 * got / poss).unwrap();
            ws.write_number(r, c + 5, 0.0).unwrap();
        }
    }
}

/// Remark's statistics of the rows (as Remark computes them: SD ÷ N; KR-20 on the number
/// right; α on the weighted item scores).
pub fn stats(b: &Book) -> (f64, f64, f64, f64, f64) {
    let n = b.students.len() as f64;
    let k = b.key.len();
    let x: Vec<Vec<bool>> = b
        .students
        .iter()
        .map(|s| (0..k).map(|q| s.answers[q] == b.key[q]).collect())
        .collect();
    let totals: Vec<f64> = b.students.iter().map(|s| b.total(s)).collect();
    let pvar = |v: &[f64]| {
        let m = v.iter().sum::<f64>() / v.len() as f64;
        v.iter().map(|a| (a - m).powi(2)).sum::<f64>() / v.len() as f64
    };
    let mean = totals.iter().sum::<f64>() / n;
    let max = totals.iter().cloned().fold(f64::MIN, f64::max);
    let nr: Vec<f64> = x
        .iter()
        .map(|r| r.iter().filter(|v| **v).count() as f64)
        .collect();
    let spq: f64 = (0..k)
        .map(|q| {
            let p = x.iter().filter(|r| r[q]).count() as f64 / n;
            p * (1.0 - p)
        })
        .sum();
    let kf = k as f64;
    let kr20 = kf / (kf - 1.0) * (1.0 - spq / pvar(&nr));
    let iv: f64 = (0..k)
        .map(|q| {
            pvar(
                &x.iter()
                    .map(|r| if r[q] { b.points[q] } else { 0.0 })
                    .collect::<Vec<_>>(),
            )
        })
        .sum();
    let alpha = kf / (kf - 1.0) * (1.0 - iv / pvar(&totals));
    (mean, pvar(&totals).sqrt(), max, kr20, alpha)
}

fn test_stats(ws: &mut Worksheet, b: &Book) {
    ws.write_string(1, 0, "Test Statistics Report").unwrap();
    ws.write_string(5, 1, "Overall").unwrap();
    ws.write_string(5, 2, "Extra Credit").unwrap();
    let (mean, sd, max, kr20, alpha) = stats(b);
    let rows: [(&str, f64); 6] = [
        ("Total Possible Points", b.possible()),
        ("Maximum Score", max),
        ("Mean Score", mean),
        ("Standard Deviation", sd),
        ("Kuder-Richardson Formula 20", kr20),
        ("Coefficient (Cronbach) Alpha", alpha),
    ];
    for (i, (l, v)) in rows.iter().enumerate() {
        ws.write_string(7 + i as u32, 0, *l).unwrap();
        ws.write_number(7 + i as u32, 1, *v).unwrap();
        ws.write_string(7 + i as u32, 2, "-").unwrap();
    }
}

/// Letters of options.
pub fn letter(o: u8) -> String {
    char::from(b'A' + o).to_string()
}
